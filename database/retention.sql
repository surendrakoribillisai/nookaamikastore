-- 4. WISHLIST PRIVACY
-- ============================================================
-- A customer's wishlist must only be returned for that customer.
-- Do NOT expose all wishlist rows to normal customers.
--
-- The application/backend should always use:
--
-- WHERE customer_id = authenticated_customer_id
--
-- Admin should not display another customer's wishlist as a
-- public/shared wishlist.


-- ============================================================
-- 5. RETENTION SUMMARY
-- ============================================================
--
-- Customer:
--   Orders/purchases visible: 3 months
--
-- Admin:
--   Orders: 1 year
--   Order items: 1 year
--   Settlements: 1 year
--
-- Wishlist:
--   Owner only
--   Database retention: 1 year
--
-- After 1 year:
--   Expired orders/order items/settlements/wishlist records
--   are removed from the database.
--
-- Customer accounts are NOT deleted by this cleanup.
